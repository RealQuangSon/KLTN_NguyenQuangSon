from __future__ import annotations

import sqlite3
import threading
from pathlib import Path


class _Rows:
    """Kết quả đã đọc hết ngay trong khóa của execute — an toàn khi dùng chéo thread.

    sqlite3 của bản Python/framework này không chịu hai thread cùng chạm connection
    (kể cả per-call): câu lệnh và fetch phải là MỘT thao tác nguyên tử."""
    __slots__ = ("_rows", "_index", "rowcount", "lastrowid")

    def __init__(self, rows, rowcount=0, lastrowid=None):
        self._rows = rows
        self._index = 0
        self.rowcount = rowcount
        self.lastrowid = lastrowid

    def fetchone(self):
        if self._index >= len(self._rows):
            return None
        row = self._rows[self._index]
        self._index += 1
        return row

    def fetchall(self):
        self._index = len(self._rows)
        return self._rows

    def __iter__(self):
        return iter(self._rows)


class Database:
    """Small SQL boundary shared by the offline and PostgreSQL repositories."""

    def __init__(self, location: str | Path):
        self.postgres = str(location).startswith(("postgresql://", "postgres://"))
        self.location = str(location)
        self.closed = False
        self.depth = 0
        self.transactions = []
        # HN-01: tool chỉ đọc chạy song song ở executor dùng chung connection này;
        # khóa tuần tự hóa từng thao tác connection (những phần không DB vẫn chồng).
        self._lock = threading.RLock()
        if self.postgres:
            self.connection = self._connect_postgres()
        else:
            if str(location) != ":memory:":
                Path(location).parent.mkdir(parents=True, exist_ok=True)
            self.connection = sqlite3.connect(str(location), check_same_thread=False, isolation_level=None)
            self.connection.row_factory = sqlite3.Row
            with self._lock:
                self.connection.execute("PRAGMA foreign_keys=ON")

    def _connect_postgres(self):
        import psycopg
        from psycopg.rows import dict_row
        return psycopg.connect(self.location, autocommit=True, row_factory=dict_row)

    def _retry_dead_connection(self, action):
        """Hosted PostgreSQL (Neon scale-to-zero, restarts) closes idle sessions. Outside a
        transaction a dead session is replaced once and the statement re-sent: the old
        socket was already gone, so the statement never reached the server. Inside a
        transaction the error propagates and the caller's unit of work fails as before."""
        import psycopg
        try:
            return action()
        except psycopg.OperationalError:
            # Never reopen a session this process closed on purpose (shutdown, failed health).
            if self.closed or self.depth or not (self.connection.closed or self.connection.broken):
                raise
            self.connection = self._connect_postgres()
            return action()

    def execute(self, sql: str, params=()):
        with self._lock:
            if self.postgres:
                sql = sql.replace("?", "%s").replace(
                    "INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
                cursor = self._retry_dead_connection(lambda: self.connection.execute(sql, params))
            else:
                cursor = self.connection.execute(sql, params)
            # psycopg raises on fetchall() for statements that return no rows (DDL, plain DML).
            rows = cursor.fetchall() if cursor.description else []
            return _Rows(rows, cursor.rowcount, getattr(cursor, "lastrowid", None))

    def executescript(self, sql: str):
        for statement in sql.split(";"):
            if statement.strip():
                self.execute(statement)

    def commit(self):
        with self._lock:
            self.connection.commit()

    def close(self):
        with self._lock:
            self.closed = True
            self.connection.close()

    def __enter__(self):
        with self._lock:
            if self.postgres:
                def begin():
                    transaction = self.connection.transaction()
                    transaction.__enter__()
                    return transaction
                # BEGIN is the first statement of the unit of work, so it is safe to retry.
                self.transactions.append(self._retry_dead_connection(begin) if self.depth == 0 else begin())
            elif self.depth == 0:
                self.connection.execute("BEGIN IMMEDIATE")
            else:
                self.connection.execute(f"SAVEPOINT hm_nested_{self.depth}")
            self.depth += 1
        return self

    def __exit__(self, kind, error, traceback):
        with self._lock:
            self.depth -= 1
            if self.postgres:
                return self.transactions.pop().__exit__(kind, error, traceback)
            if self.depth == 0:
                self.connection.rollback() if kind else self.connection.commit()
            else:
                name = f"hm_nested_{self.depth}"
                if kind:
                    self.connection.execute(f"ROLLBACK TO SAVEPOINT {name}")
                self.connection.execute(f"RELEASE SAVEPOINT {name}")
        return False
